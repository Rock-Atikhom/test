def adjust_brightness_contrast(image_rgb, alpha=1.2, beta=15):
    """alpha controls contrast; beta controls brightness."""
    return cv2.convertScaleAbs(image_rgb, alpha=alpha, beta=beta)


def equalize_luminance(image_rgb, method='clahe'):
    lab = cv2.cvtColor(image_rgb, cv2.COLOR_RGB2LAB)
    l_channel, a_channel, b_channel = cv2.split(lab)

    if method == 'clahe':
        clahe = cv2.createCLAHE(clipLimit=2.0, tileGridSize=(8, 8))
        l_equalized = clahe.apply(l_channel)
    else:
        l_equalized = cv2.equalizeHist(l_channel)

    lab_equalized = cv2.merge((l_equalized, a_channel, b_channel))
    return cv2.cvtColor(lab_equalized, cv2.COLOR_LAB2RGB)


def iqr_bounds(values, multiplier=1.5):
    values = np.asarray(values, dtype=np.float32)
    if values.size == 0:
        return np.nan, np.nan
    q1 = np.percentile(values, 25)
    q3 = np.percentile(values, 75)
    iqr = q3 - q1
    return q1 - multiplier * iqr, q3 + multiplier * iqr


def remove_iqr_outliers(df, column, multiplier=1.5):
    lower, upper = iqr_bounds(df[column].dropna().to_numpy(), multiplier=multiplier)
    if np.isnan(lower) or np.isnan(upper):
        return df.copy(), lower, upper
    mask = df[column].between(lower, upper, inclusive='both')
    return df.loc[mask].copy(), lower, upper

