"""## 9-11. Feature Matching, Homography, and Blending

Use ORB when you need a fast, patent-free baseline. Use SIFT when available and accuracy matters more than speed. Estimate homography with RANSAC so bad matches do not dominate the transform.
"""

def create_feature_detector(method='ORB', max_features=2000):
    method = method.upper()
    if method == 'SIFT' and hasattr(cv2, 'SIFT_create'):
        return cv2.SIFT_create(nfeatures=max_features), cv2.NORM_L2
    return cv2.ORB_create(nfeatures=max_features), cv2.NORM_HAMMING


def match_features(image_a_rgb, image_b_rgb, method='ORB', ratio=0.75, max_features=2000):
    detector, norm_type = create_feature_detector(method, max_features=max_features)
    gray_a = to_gray(image_a_rgb)
    gray_b = to_gray(image_b_rgb)
    kp_a, desc_a = detector.detectAndCompute(gray_a, None)
    kp_b, desc_b = detector.detectAndCompute(gray_b, None)

    if desc_a is None or desc_b is None or len(kp_a) < 4 or len(kp_b) < 4:
        return kp_a, kp_b, []

    matcher = cv2.BFMatcher(norm_type)
    knn = matcher.knnMatch(desc_a, desc_b, k=2)
    good = []
    for pair in knn:
        if len(pair) == 2:
            m, n = pair
            if m.distance < ratio * n.distance:
                good.append(m)
    return kp_a, kp_b, good


def estimate_homography(kp_a, kp_b, matches, reproj_threshold=4.0):
    if len(matches) < 4:
        return None, None
    pts_a = np.float32([kp_a[m.queryIdx].pt for m in matches]).reshape(-1, 1, 2)
    pts_b = np.float32([kp_b[m.trainIdx].pt for m in matches]).reshape(-1, 1, 2)
    H, mask = cv2.findHomography(pts_a, pts_b, cv2.RANSAC, reproj_threshold)
    return H, mask


def alpha_blend(image_a_rgb, image_b_rgb, alpha=0.5):
    if image_a_rgb.shape != image_b_rgb.shape:
        image_b_rgb = cv2.resize(image_b_rgb, (image_a_rgb.shape[1], image_a_rgb.shape[0]))
    return cv2.addWeighted(image_a_rgb, alpha, image_b_rgb, 1 - alpha, 0)

