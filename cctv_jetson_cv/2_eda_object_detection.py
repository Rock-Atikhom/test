"""# Dataset Loading
We will now wrap our cleaned image lists and labels into a PyTorch Dataset. This class will handle loading images from disk and applying the `letterbox_image` transformation (resizing and padding) to every image automatically.
"""

import torch
from torch.utils.data import Dataset, DataLoader

class VeRiDataset(Dataset):
    def __init__(self, image_list, labels, directory, size=(224, 224)):
        if len(image_list) != len(labels):
            raise ValueError(f"image_list and labels must have the same length, got {len(image_list)} and {len(labels)}")
        self.image_list = image_list
        self.labels = labels
        self.directory = directory
        self.size = size

    def __len__(self):
        return len(self.image_list)

    def __getitem__(self, idx):
        img_name = self.image_list[idx]
        label = self.labels[idx]
        img_path = os.path.join(self.directory, img_name)

        image = cv2.imread(img_path)
        if image is None:
            raise FileNotFoundError(f"Could not read image: {img_path}")
        image = cv2.cvtColor(image, cv2.COLOR_BGR2RGB)

        image = letterbox_image(image, size=self.size)

        image = image.astype(np.float32) / 255.0
        image = np.transpose(image, (2, 0, 1))

        return torch.from_numpy(image), torch.tensor(label, dtype=torch.long)

