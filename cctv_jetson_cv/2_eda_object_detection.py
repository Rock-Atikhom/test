"""## 14-16. Centroid Tracking, Kalman Filters, and Optical Flow

Centroid tracking is a simple object identity baseline. A Kalman filter smooths noisy detections and predicts short occlusions. Optical flow estimates pixel motion between adjacent frames.
"""

class CentroidTracker:
    def __init__(self, max_disappeared=10, max_distance=80):
        self.next_object_id = 0
        self.objects = OrderedDict()
        self.disappeared = OrderedDict()
        self.max_disappeared = max_disappeared
        self.max_distance = max_distance

    def register(self, centroid):
        self.objects[self.next_object_id] = centroid
        self.disappeared[self.next_object_id] = 0
        self.next_object_id += 1

    def deregister(self, object_id):
        del self.objects[object_id]
        del self.disappeared[object_id]

    def update(self, boxes):
        if len(boxes) == 0:
            for object_id in list(self.disappeared.keys()):
                self.disappeared[object_id] += 1
                if self.disappeared[object_id] > self.max_disappeared:
                    self.deregister(object_id)
            return self.objects

        input_centroids = np.zeros((len(boxes), 2), dtype='int')
        for i, (x1, y1, x2, y2) in enumerate(boxes):
            input_centroids[i] = ((x1 + x2) // 2, (y1 + y2) // 2)

        if len(self.objects) == 0:
            for centroid in input_centroids:
                self.register(tuple(centroid))
            return self.objects

        object_ids = list(self.objects.keys())
        object_centroids = np.array(list(self.objects.values()))
        distances = np.linalg.norm(object_centroids[:, None, :] - input_centroids[None, :, :], axis=2)

        rows = distances.min(axis=1).argsort()
        cols = distances.argmin(axis=1)[rows]
        used_rows, used_cols = set(), set()

        for row, col in zip(rows, cols):
            if row in used_rows or col in used_cols or distances[row, col] > self.max_distance:
                continue
            object_id = object_ids[row]
            self.objects[object_id] = tuple(input_centroids[col])
            self.disappeared[object_id] = 0
            used_rows.add(row)
            used_cols.add(col)

        unused_rows = set(range(distances.shape[0])) - used_rows
        unused_cols = set(range(distances.shape[1])) - used_cols

        for row in unused_rows:
            object_id = object_ids[row]
            self.disappeared[object_id] += 1
            if self.disappeared[object_id] > self.max_disappeared:
                self.deregister(object_id)

        for col in unused_cols:
            self.register(tuple(input_centroids[col]))

        return self.objects


def make_kalman_filter(initial_x, initial_y):
    kf = cv2.KalmanFilter(4, 2)
    kf.measurementMatrix = np.array([[1, 0, 0, 0], [0, 1, 0, 0]], np.float32)
    kf.transitionMatrix = np.array([[1, 0, 1, 0], [0, 1, 0, 1], [0, 0, 1, 0], [0, 0, 0, 1]], np.float32)
    kf.processNoiseCov = np.eye(4, dtype=np.float32) * 0.03
    kf.measurementNoiseCov = np.eye(2, dtype=np.float32) * 0.5
    kf.statePre = np.array([[initial_x], [initial_y], [0], [0]], np.float32)
    kf.statePost = kf.statePre.copy()
    return kf


def track_with_kalman(kf, measured_x=None, measured_y=None):
    prediction = kf.predict()
    if measured_x is not None and measured_y is not None:
        measurement = np.array([[np.float32(measured_x)], [np.float32(measured_y)]])
        corrected = kf.correct(measurement)
        return tuple(corrected[:2].ravel()), tuple(prediction[:2].ravel())
    return None, tuple(prediction[:2].ravel())


def dense_optical_flow(prev_rgb, next_rgb):
    prev_gray = to_gray(prev_rgb)
    next_gray = to_gray(next_rgb)
    flow = cv2.calcOpticalFlowFarneback(prev_gray, next_gray, None, 0.5, 3, 15, 3, 5, 1.2, 0)
    magnitude, angle = cv2.cartToPolar(flow[..., 0], flow[..., 1])
    hsv = np.zeros((*prev_gray.shape, 3), dtype=np.uint8)
    hsv[..., 0] = angle * 180 / np.pi / 2
    hsv[..., 1] = 255
    hsv[..., 2] = cv2.normalize(magnitude, None, 0, 255, cv2.NORM_MINMAX)
    return cv2.cvtColor(hsv, cv2.COLOR_HSV2RGB), flow

