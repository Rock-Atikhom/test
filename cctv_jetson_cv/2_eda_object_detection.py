"""# Image Resizing with Letterboxing (Padding)"""

def letterbox_image(image, size=(224, 224)):
    """Resize an RGB image with gray padding while preserving aspect ratio."""
    if image is None:
        raise ValueError("letterbox_image received None instead of an image array")

    ih, iw = image.shape[:2]
    w, h = size
    scale = min(w / iw, h / ih)
    nw = max(1, int(iw * scale))
    nh = max(1, int(ih * scale))

    image_resized = cv2.resize(image, (nw, nh), interpolation=cv2.INTER_AREA)

    if image.ndim == 2:
        new_image = np.full((h, w), 128, dtype=np.uint8)
        top = (h - nh) // 2
        left = (w - nw) // 2
        new_image[top:top+nh, left:left+nw] = image_resized
    else:
        channels = image.shape[2]
        new_image = np.full((h, w, channels), 128, dtype=np.uint8)
        top = (h - nh) // 2
        left = (w - nw) // 2
        new_image[top:top+nh, left:left+nw, :] = image_resized

    return new_image

