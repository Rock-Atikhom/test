def get_aspect_ratios(image_list, directory, sample_size=5000, seed=42):
    ratios = []
    if not image_list:
        return ratios

    rng = np.random.default_rng(seed)
    sample_size = min(len(image_list), sample_size)
    sample = rng.choice(image_list, sample_size, replace=False)

    for img_name in tqdm(sample, desc="Calculating Ratios"):
        img_path = os.path.join(directory, img_name)
        img_temp = cv2.imread(img_path)
        if img_temp is not None:
            h, w = img_temp.shape[:2]
            if h > 0:
                ratios.append(w / h)
    return ratios

