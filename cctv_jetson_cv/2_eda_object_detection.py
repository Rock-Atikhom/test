def classify_vehicle_crop_cached(
    frame_bgr,
    box_xyxy,
    classifier_model,
    track_id,
    label_cache,
    frame_index,
    classify_every_n_frames=10,
    imgsz=224,
):
    """Classify a tracked vehicle crop, but cache the label to save compute."""
    cached = label_cache.get(track_id)
    if cached is not None and frame_index % classify_every_n_frames != 0:
        return cached

    result = classify_vehicle_crop(frame_bgr, box_xyxy, classifier_model, imgsz=imgsz)
    if result is None:
        return cached

    vehicle_id, confidence = result
    label_cache[track_id] = (vehicle_id, confidence)
    return label_cache[track_id]


def draw_tracking_with_custom_id(
    frame_bgr,
    result,
    track_history,
    previous_centers,
    previous_times,
    classifier_model,
    label_cache,
    frame_index,
    classify_every_n_frames=10,
    max_trail=30,
):
    now = time.time()
    annotated = frame_bgr.copy()

    if result.boxes is None or result.boxes.id is None:
        return annotated

    boxes = result.boxes.xyxy.cpu().numpy()
    track_ids = result.boxes.id.int().cpu().tolist()
    class_ids = result.boxes.cls.int().cpu().tolist()
    confidences = result.boxes.conf.cpu().numpy()

    for box, track_id, class_id, det_conf in zip(boxes, track_ids, class_ids, confidences):
        x1, y1, x2, y2 = box.astype(int)
        cx, cy = center_of_box_xyxy((x1, y1, x2, y2))

        track_history[track_id].append((cx, cy))
        if len(track_history[track_id]) > max_trail:
            track_history[track_id].popleft()

        speed_px_per_sec = 0.0
        direction = ''
        if track_id in previous_centers:
            prev_cx, prev_cy = previous_centers[track_id]
            dt = max(now - previous_times.get(track_id, now), 1e-6)
            dx, dy = cx - prev_cx, cy - prev_cy
            speed_px_per_sec = math.sqrt(dx * dx + dy * dy) / dt
            direction = ('right' if dx > 0 else 'left') if abs(dx) > abs(dy) else ('down' if dy > 0 else 'up')

        previous_centers[track_id] = (cx, cy)
        previous_times[track_id] = now

        custom_pred = classify_vehicle_crop_cached(
            frame_bgr,
            (x1, y1, x2, y2),
            classifier_model,
            track_id,
            label_cache,
            frame_index,
            classify_every_n_frames=classify_every_n_frames,
        )

        class_name = model.names.get(class_id, str(class_id))
        if custom_pred is None:
            custom_text = 'custom ID: ...'
        else:
            vehicle_id, cls_conf = custom_pred
            custom_text = f'custom ID: {vehicle_id} ({cls_conf:.2f})'

        cv2.rectangle(annotated, (x1, y1), (x2, y2), (0, 255, 0), 2)
        cv2.circle(annotated, (cx, cy), 4, (0, 0, 255), -1)
        cv2.putText(annotated, f'Track {track_id} {class_name} det:{det_conf:.2f}', (x1, max(20, y1 - 42)), cv2.FONT_HERSHEY_SIMPLEX, 0.52, (255, 255, 255), 2, cv2.LINE_AA)
        cv2.putText(annotated, custom_text, (x1, max(20, y1 - 24)), cv2.FONT_HERSHEY_SIMPLEX, 0.52, (255, 255, 0), 2, cv2.LINE_AA)
        motion = f'{direction} {speed_px_per_sec:.0f}px/s' if direction else 'new track'
        cv2.putText(annotated, motion, (x1, max(20, y1 - 6)), cv2.FONT_HERSHEY_SIMPLEX, 0.48, (0, 255, 255), 2, cv2.LINE_AA)

        trail = list(track_history[track_id])
        for i in range(1, len(trail)):
            cv2.line(annotated, trail[i - 1], trail[i], (0, 255, 255), 2)

    return annotated

