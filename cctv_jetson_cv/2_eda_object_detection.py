RANDOM_SEED = 42


def vehicle_id_from_filename(filename):
    return filename.split('_')[0]


def collect_images_by_id(image_names):
    by_id = {}
    for name in image_names:
        vehicle_id = vehicle_id_from_filename(name)
        by_id.setdefault(vehicle_id, []).append(name)
    return by_id


def prepare_yolo_cls_dataset(
    image_names,
    source_dir,
    output_dir=YOLO_CLS_DATASET_DIR,
    max_classes=MAX_CLASSES_FOR_QUICK_TEST,
    max_images_per_class=MAX_IMAGES_PER_CLASS,
    min_images_per_class=MIN_IMAGES_PER_CLASS,
    val_ratio=VAL_RATIO,
    seed=RANDOM_SEED,
):
    rng = np.random.default_rng(seed)
    output_dir = Path(output_dir)
    source_dir = Path(source_dir)

    if output_dir.exists():
        shutil.rmtree(output_dir)

    by_id = collect_images_by_id(image_names)
    eligible = {vid: imgs for vid, imgs in by_id.items() if len(imgs) >= min_images_per_class}
    selected_ids = sorted(eligible.keys(), key=lambda vid: len(eligible[vid]), reverse=True)
    if max_classes is not None:
        selected_ids = selected_ids[:max_classes]

    class_counts = []
    for vehicle_id in selected_ids:
        imgs = list(eligible[vehicle_id])
        rng.shuffle(imgs)
        if max_images_per_class is not None:
            imgs = imgs[:max_images_per_class]

        n_val = max(1, int(round(len(imgs) * val_ratio)))
        val_imgs = imgs[:n_val]
        train_imgs = imgs[n_val:]

        if not train_imgs:
            train_imgs, val_imgs = imgs[:-1], imgs[-1:]

        for split, split_imgs in [('train', train_imgs), ('val', val_imgs)]:
            class_dir = output_dir / split / vehicle_id
            class_dir.mkdir(parents=True, exist_ok=True)
            for img_name in split_imgs:
                src = source_dir / img_name
                dst = class_dir / img_name
                if src.exists():
                    shutil.copy2(src, dst)

        class_counts.append({
            'vehicle_id': vehicle_id,
            'train_images': len(train_imgs),
            'val_images': len(val_imgs),
            'total_images': len(imgs),
        })

    df_cls_summary = pd.DataFrame(class_counts)
    return output_dir, df_cls_summary

