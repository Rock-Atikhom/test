def classify_vehicle_crop(frame_bgr, box_xyxy, classifier_model, imgsz=224):
    x1, y1, x2, y2 = [int(v) for v in box_xyxy]
    height, width = frame_bgr.shape[:2]
    x1 = max(0, min(x1, width - 1))
    x2 = max(0, min(x2, width - 1))
    y1 = max(0, min(y1, height - 1))
    y2 = max(0, min(y2, height - 1))

    if x2 <= x1 or y2 <= y1:
        return None

    crop_bgr = frame_bgr[y1:y2, x1:x2]
    pred = classifier_model.predict(crop_bgr, imgsz=imgsz, verbose=False)[0]
    top1_idx = int(pred.probs.top1)
    top1_conf = float(pred.probs.top1conf)
    return classifier_model.names[top1_idx], top1_conf

