def get_max_side_records(image_list, directory, dataset_name):
    records = []
    for img_name in tqdm(image_list, desc=f"Scanning {dataset_name}"):
        img_path = os.path.join(directory, img_name)
        img_temp = cv2.imread(img_path)
        if img_temp is not None:
            h, w = img_temp.shape[:2]
            records.append({
                'dataset': dataset_name,
                'image': img_name,
                'width': w,
                'height': h,
                'max_side': max(h, w),
            })
    return records

