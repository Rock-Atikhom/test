def process_frame(frame_bgr):
    gray = cv2.cvtColor(frame_bgr, cv2.COLOR_BGR2GRAY)
    edges = cv2.Canny(gray, 80, 160)
    overlay = frame_bgr.copy()
    overlay[edges > 0] = (0, 255, 255)
    return overlay


