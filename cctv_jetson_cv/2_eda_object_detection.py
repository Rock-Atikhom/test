"""## 7-8. Blurring, Low-Sharpness Removal, and Canny Edge Detection

Gaussian blur is a good default for sensor noise. Median blur is useful for salt-and-pepper noise. For blur filtering, removing the bottom 5% by Laplacian variance is a defensible starting point.
"""

def gaussian_blur(image_rgb, kernel_size=5, sigma=0):
    kernel_size = kernel_size if kernel_size % 2 == 1 else kernel_size + 1
    return cv2.GaussianBlur(image_rgb, (kernel_size, kernel_size), sigma)


def median_blur(image_rgb, kernel_size=5):
    kernel_size = kernel_size if kernel_size % 2 == 1 else kernel_size + 1
    return cv2.medianBlur(image_rgb, kernel_size)


def laplacian_sharpness(image_rgb):
    return cv2.Laplacian(to_gray(image_rgb), cv2.CV_64F).var()


def remove_low_sharpness_outliers(image_names, directory, percentile=5):
    scores = []
    readable_names = []
    for name in tqdm(image_names, desc='Scoring sharpness'):
        img_bgr = cv2.imread(os.path.join(directory, name))
        if img_bgr is None:
            continue
        img_rgb = cv2.cvtColor(img_bgr, cv2.COLOR_BGR2RGB)
        scores.append(laplacian_sharpness(img_rgb))
        readable_names.append(name)

    if not scores:
        return [], np.nan, pd.DataFrame(columns=['image', 'sharpness'])

    threshold = np.percentile(scores, percentile)
    df_scores = pd.DataFrame({'image': readable_names, 'sharpness': scores})
    kept = df_scores.loc[df_scores['sharpness'] >= threshold, 'image'].tolist()
    return kept, threshold, df_scores


